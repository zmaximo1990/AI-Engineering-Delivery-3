from enum import Enum

from pydantic import BaseModel, Field

from constants import DEFAULT_MAX_TOKENS, DEFAULT_TEMPERATURE


class Provider(str, Enum):
    OPENAI = "openai"
    ANTHROPIC = "anthropic"
    GEMINI = "gemini"


class LLMConfig(BaseModel):
    """Provider, model, and sampling settings for one RAG run."""

    provider: Provider
    model: str | None = None
    max_tokens: int = Field(default=DEFAULT_MAX_TOKENS, gt=0)
    temperature: float = Field(default=DEFAULT_TEMPERATURE, ge=0.0, le=2.0)


class LLMAnswer(BaseModel):
    """Answer the model must produce from the retrieved context only."""

    answer: str = Field(
        ...,
        min_length=1,
        description=(
            "Answer to the user question based exclusively on the CONTEXT. "
            "If the information is not in the context, say that you do not "
            "have access to that information in the available documents."
        ),
    )


class RAGResponse(BaseModel):
    """Final object returned by get_rag_response.

    The answer comes from the model. Sources and the fragment count come
    from the retrieved documents, so they are not generated by the model.
    """

    answer: str = Field(
        description="Answer provided by the model based on the context."
    )
    sources: list[str] = Field(
        description="Source files of the fragments used as context."
    )
    retrieved_fragments: int = Field(
        ge=0,
        description="Number of fragments retrieved and used as context."
    )